/*
 * This file is hand-authored rather than generated because the aroid trade
 * doesn't organize itself the way a taxonomy does. Growers, sellers, and the
 * people typing into this app's search box think in four levels: family,
 * then genus, then a shelf label, then the actual cultivar or species they
 * want to add. The "group" level below - things like 'Rare Alocasias' or
 * 'Variegated Philodendrons' - is not a botanical rank. Nothing in
 * international nomenclature recognizes a "Jewel Alocasia" clade. It exists
 * because that's the aisle someone reaches for: a beginner with a Pothos
 * wants the common shelf, a collector chasing a stable variegate wants the
 * variegated shelf, and forcing both into a strict genus/species tree would
 * make the search worse at the one job it has, which is matching what a
 * person actually typed to the plant they meant.
 *
 * genus, group, and family are repeated on every single entry below even
 * though that's redundant with the tree structure this file exports. That
 * redundancy is deliberate, not an oversight. When a user adds a plant to
 * their collection, the app copies the matching CatalogEntry onto the saved
 * plant as a snapshot - it does not keep a live pointer back into this file.
 * That snapshot has to be self-describing on its own, because this file is
 * free to be reorganized, re-grouped, or have entries renamed later without
 * silently rewriting history for plants people already own. A saved plant
 * should still say "Alocasia baginda, Rare Alocasias, Aroids" even if a
 * future edit here moves Dragon Scale into some new "Baginda Cultivars"
 * group.
 *
 * A note on scientific accuracy: aroid cultivar names in the hobby trade
 * routinely outrun what taxonomists have formally settled. Where a plant's
 * true species parentage is genuinely unresolved or it's a nursery hybrid
 * without a published binomial, this file uses the genus with 'sp.' or the
 * closest well-supported species rather than inventing an epithet that
 * would look authoritative but isn't real.
 */

