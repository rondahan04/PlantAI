import type { CatalogFamily } from './catalogTypes';

/*
 * The rest of the houseplant world, kept out of the aroid file on purpose.
 * Aroids (Monstera, Philodendron, Alocasia, Anthurium and kin) are what most
 * of this app's users are actually shopping for, and that file is already
 * dense with cultivars; folding ferns, prayer plants, hoyas, cacti and every
 * other shelf of a plant shop into the same file would make both halves hard
 * to scan and harder to review. So everything that is not an aroid lives
 * here instead.
 *
 * "family" below is a shelf label, not a strict botanical rank. Real
 * botanical families would scatter Sansevieria (Asparagaceae) away from
 * Crassula and Echeveria (Crassulaceae, Aizoaceae) even though a grower
 * shopping for "succulents" wants all three on the same page, and it would
 * separate Calathea from Ctenanthe even though nobody browsing "prayer
 * plants" cares that one got reclassified into Goeppertia and the other
 * didn't. So the grouping here follows how a plant shop actually organizes
 * its tables and how a person searching the catalog actually thinks, not
 * APG taxonomy. `scientificName` still carries the real, current accepted
 * binomial for each entry; `genus` and `family` are the shelf the user
 * looks on, which is why Snake Plant sits under genus Sansevieria and
 * family Succulents even though its accepted genus is now Dracaena.
 */

